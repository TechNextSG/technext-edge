import { describe, it, expect } from "vitest";
import {
  PROVIDER_REGISTRY,
  PROVIDER_KINDS,
  MODEL_CATALOG,
  isKnownModel,
  choiceFromName,
  settingsFromEnv,
  buildProvider,
  type ProviderKind,
  type ProviderSettings,
} from "../../src/infra/providers/registry.ts";

describe("T4: Registry as the single source (ai/src/infra/providers/registry.ts)", () => {
  it("defines PROVIDER_REGISTRY with all 3 providers and rich metadata", () => {
    expect(PROVIDER_REGISTRY).toBeDefined();
    expect(PROVIDER_KINDS).toEqual(["gemini", "deepseek", "anthropic"]);

    for (const kind of PROVIDER_KINDS) {
      const entry = PROVIDER_REGISTRY[kind];
      expect(entry.kind).toBe(kind);
      expect(typeof entry.label).toBe("string");
      expect(typeof entry.defaultModel).toBe("string");
      expect(Array.isArray(entry.models)).toBe(true);
      expect(entry.modelPattern instanceof RegExp).toBe(true);
      expect(Array.isArray(entry.aliases)).toBe(true);
      expect(Array.isArray(entry.fallbackOrder)).toBe(true);
      expect(typeof entry.envKeys.apiKey).toBe("string");
      expect(typeof entry.create).toBe("function");
    }
  });

  it("derives MODEL_CATALOG and isKnownModel directly from registry entries", () => {
    expect(MODEL_CATALOG.gemini).toBe(PROVIDER_REGISTRY.gemini.models);
    expect(MODEL_CATALOG.deepseek).toBe(PROVIDER_REGISTRY.deepseek.models);
    expect(MODEL_CATALOG.anthropic).toBe(PROVIDER_REGISTRY.anthropic.models);

    // Tests known models and pattern matching
    expect(isKnownModel("anthropic", "claude-haiku-5-5")).toBe(true);
    expect(isKnownModel("anthropic", "claude-custom-enterprise")).toBe(true);
    expect(isKnownModel("anthropic", "gpt-4o")).toBe(false);

    expect(isKnownModel("gemini", "gemini-3.1-flash-lite")).toBe(true);
    expect(isKnownModel("gemini", "gemini-custom-model")).toBe(true);
    expect(isKnownModel("gemini", "deepseek-flash")).toBe(false);

    expect(isKnownModel("deepseek", "deepseek-flash")).toBe(true);
    expect(isKnownModel("deepseek", "deepseek-custom-70b")).toBe(true);
    expect(isKnownModel("deepseek", "unknown")).toBe(false);
  });

  it("resolves choiceFromName using aliases and kind:model format", () => {
    // kind:model
    expect(choiceFromName("gemini:gemini-exp-1206", {})).toEqual({
      provider: "gemini",
      model: "gemini-exp-1206",
    });
    expect(choiceFromName("claude:claude-sonnet-custom", {})).toEqual({
      provider: "anthropic",
      model: "claude-sonnet-custom",
    });

    // aliases
    expect(choiceFromName("gemini-flash-lite", {})).toEqual({
      provider: "gemini",
      model: "gemini-3.1-flash-lite",
    });
    expect(choiceFromName("gemini-pro", {})).toEqual({
      provider: "gemini",
      model: "gemini-2.5-pro",
    });
    expect(choiceFromName("deepseek", {})).toEqual({
      provider: "deepseek",
      model: "deepseek-flash",
    });
    expect(choiceFromName("anthropic", {})).toEqual({
      provider: "anthropic",
      model: "claude-haiku-5-5",
    });
  });

  it("settingsFromEnv determines fallback using registry fallbackOrder", () => {
    // When primary is anthropic, fallbackOrder is ["gemini", "deepseek"]
    const s1 = settingsFromEnv({
      EXTRACTOR_PROVIDER: "anthropic",
      ANTHROPIC_API_KEY: "ant-key",
      DEEPSEEK_GATEWAY_KEY: "ds-key",
      DEEPSEEK_BASE_URL: "https://gateway.example.com",
    });
    expect(s1.primary.provider).toBe("anthropic");
    // gemini has no key, so deepseek is chosen as next in fallbackOrder
    expect(s1.fallback?.provider).toBe("deepseek");

    // When primary is gemini, fallbackOrder is ["deepseek", "anthropic"]
    const s2 = settingsFromEnv({
      EXTRACTOR_PROVIDER: "gemini",
      GEMINI_API_KEY: "gem-key",
      ANTHROPIC_API_KEY: "ant-key",
    });
    expect(s2.primary.provider).toBe("gemini");
    // deepseek has no key/url, so anthropic is chosen
    expect(s2.fallback?.provider).toBe("anthropic");
  });

  it("restricts Anthropic catalog to claude-haiku-5-5 and claude-sonnet-5-5 and drops claude-3-5-haiku alias", () => {
    expect(PROVIDER_REGISTRY.anthropic.models).toEqual(["claude-haiku-5-5", "claude-sonnet-5-5"]);
    expect(PROVIDER_REGISTRY.anthropic.aliases).not.toContain("claude-3-5-haiku");
    expect(choiceFromName("claude-3-5-haiku", {})).toBeNull();
  });

  it("declares requiresBaseUrl boolean on each entry", () => {
    expect(PROVIDER_REGISTRY.deepseek.requiresBaseUrl).toBe(true);
    expect(PROVIDER_REGISTRY.gemini.requiresBaseUrl).toBe(false);
    expect(PROVIDER_REGISTRY.anthropic.requiresBaseUrl).toBe(false);
  });

  it("supports baseUrls map per kind generated by registry loop", () => {
    const s = settingsFromEnv({
      EXTRACTOR_PROVIDER: "deepseek",
      DEEPSEEK_GATEWAY_KEY: "ds-key",
      DEEPSEEK_BASE_URL: "https://gateway.example.com/v1",
      ANTHROPIC_BASE_URL: "https://anthropic.proxy.com",
    });

    expect(s.baseUrls?.deepseek).toBe("https://gateway.example.com/v1");
    expect(s.baseUrls?.anthropic).toBe("https://anthropic.proxy.com");

    // buildProvider respects baseUrls
    const p = buildProvider(
      { provider: "deepseek", model: "deepseek-flash" },
      "test-key",
      { baseUrls: { deepseek: "https://custom.gateway.internal" } },
    );
    expect(p.id).toBe("deepseek-gateway:deepseek-flash");
  });
});
